class LegacyPromptSettings(BaseSettings):
    OPENAI_CUSTOM_PROMPT_DIR: str | None = None

    model_config = SettingsConfigDict(extra="ignore")


def get_custom_prompt_dir() -> Path | None:
    settings = LegacyPromptSettings(
        _env_file=ENV,
        _env_file_encoding="utf-8",
        _secrets_dir=get_secrets_dir(),
    )
    if not settings.OPENAI_CUSTOM_PROMPT_DIR:
        return None

    custom_dir = Path(settings.OPENAI_CUSTOM_PROMPT_DIR)
    if not custom_dir.is_dir():
        logger.warning(f"OPENAI_CUSTOM_PROMPT_DIR is not a directory, skipping custom prompts: {custom_dir}")
        return None

    return custom_dir


def read_custom_prompts(custom_dir: Path) -> dict[str, str]:
    """Prompt name -> content, for every non-empty custom prompt file"""
    prompts: dict[str, str] = {}
    for relative_path, name in LEGACY_PROMPT_FILES.items():
        try:
            content = (custom_dir / relative_path).read_text()
        except OSError:
            continue

        if content.strip():
            prompts[name] = content

    for path in custom_dir.rglob("*.txt"):
        if path.relative_to(custom_dir).as_posix() not in LEGACY_PROMPT_FILES:
            logger.info(f"Skipping custom prompt file that is no longer used: {path}")

    return prompts


def hash_built_in_prompt(name: str) -> str | None:
    category, prompt = name.split(".")
    try:
        content = (BUILT_IN_PROMPTS_DIR / category / f"{prompt}.txt").read_text()
    except OSError:
        return None

    # Must match how OpenAIService hashes the built-in prompt
    return hashlib.sha256(content.encode()).hexdigest()


