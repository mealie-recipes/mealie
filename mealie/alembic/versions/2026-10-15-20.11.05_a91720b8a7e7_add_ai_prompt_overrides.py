def migrate_custom_prompt_files() -> None:
    """Import legacy OPENAI_CUSTOM_PROMPT_DIR files into every group as prompt overrides"""
    if not (custom_dir := get_custom_prompt_dir()):
        return

    prompts = read_custom_prompts(custom_dir)
    if not prompts:
        return

    conn = op.get_bind()
    settings_ids = conn.execute(sa.text("SELECT id FROM ai_provider_settings")).scalars().all()
    for name, content in prompts.items():
        logger.info(f"Migrating custom prompt '{name}' to {len(settings_ids)} group(s)")
        base_prompt_hash = hash_built_in_prompt(name)
        for settings_id in settings_ids:
            conn.execute(
                sa.text(
                    "INSERT INTO ai_prompt_overrides (id, settings_id, name, mode, content, base_prompt_hash) "
                    "VALUES (:id, :settings_id, :name, :mode, :content, :base_prompt_hash)"
                ),
                {
                    "id": generate_id(),
                    "settings_id": settings_id,
                    "name": name,
                    "mode": "override",
                    "content": content,
                    "base_prompt_hash": base_prompt_hash,
                },
            )


